CREATE UNIQUE INDEX task_version_pending ON task_version(task_id) WHERE publication_state IN ('PENDING','ABORTING');
CREATE INDEX task_bank_created ON task(created_at DESC,id DESC) WHERE deleted_at IS NULL AND current_version_id IS NOT NULL;
CREATE INDEX task_bank_teacher ON task(teacher_id,created_at DESC,id DESC) WHERE deleted_at IS NULL AND current_version_id IS NOT NULL;
CREATE INDEX task_bank_subject ON task(subject_id,created_at DESC,id DESC) WHERE deleted_at IS NULL AND current_version_id IS NOT NULL;
CREATE INDEX task_bank_imported ON task(created_at DESC,id DESC) WHERE deleted_at IS NULL AND current_version_id IS NOT NULL AND source_id IS NOT NULL;
CREATE INDEX task_copy_source ON task(copied_from_task_id) WHERE copied_from_task_id IS NOT NULL;

CREATE TABLE task_version_exam_position (
    task_version_id uuid NOT NULL REFERENCES task_version(id) ON DELETE CASCADE,
    exam_position_id uuid NOT NULL REFERENCES exam_position(id),
    PRIMARY KEY (task_version_id,exam_position_id)
);
CREATE INDEX task_version_position_lookup ON task_version_exam_position(exam_position_id,task_version_id);

CREATE TABLE task_version_topic (
    task_version_id uuid NOT NULL REFERENCES task_version(id) ON DELETE CASCADE,
    topic_id integer NOT NULL REFERENCES topic(id),
    PRIMARY KEY (task_version_id,topic_id)
);
CREATE INDEX task_version_topic_lookup ON task_version_topic(topic_id,task_version_id);

CREATE TABLE task_version_file (
    task_version_id uuid NOT NULL REFERENCES task_version(id) ON DELETE CASCADE,
    file_id uuid NOT NULL REFERENCES stored_file(id),
    used_in_statement boolean NOT NULL,
    used_in_explanation boolean NOT NULL,
    PRIMARY KEY (task_version_id,file_id),
    CHECK (used_in_statement OR used_in_explanation)
);
CREATE INDEX task_version_file_lookup ON task_version_file(file_id,task_version_id);

CREATE TABLE deleted_imported_task (
    source_id integer NOT NULL REFERENCES import_source(id),
    external_key text NOT NULL,
    deleted_by uuid NOT NULL,
    deleted_at timestamptz NOT NULL,
    PRIMARY KEY (source_id,external_key)
);
