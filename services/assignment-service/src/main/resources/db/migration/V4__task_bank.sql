CREATE TABLE task (
    id uuid PRIMARY KEY,
    teacher_id uuid,
    subject_id smallint NOT NULL REFERENCES subject(id),
    source_id integer REFERENCES import_source(id),
    external_key text CHECK (length(external_key) BETWEEN 1 AND 1000),
    manual_override boolean NOT NULL DEFAULT false,
    current_version_id uuid,
    copied_from_task_id uuid REFERENCES task(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL,
    deleted_at timestamptz,
    UNIQUE (source_id,external_key),
    CHECK ((teacher_id IS NOT NULL AND source_id IS NULL AND external_key IS NULL AND NOT manual_override)
        OR (teacher_id IS NULL AND source_id IS NOT NULL AND external_key IS NOT NULL))
);

CREATE TABLE task_version (
    id uuid PRIMARY KEY,
    task_id uuid NOT NULL REFERENCES task(id),
    version integer NOT NULL CHECK (version > 0),
    statement text NOT NULL CHECK (length(statement) BETWEEN 1 AND 20000),
    explanation text CHECK (length(explanation) <= 20000),
    answer_type text NOT NULL CHECK (answer_type IN ('TEXT','NUMBER','SINGLE_CHOICE','MULTIPLE_CHOICE','MATCHING','FILES')),
    answer_config jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(answer_config) = 'object'),
    correct_answer jsonb,
    max_score integer NOT NULL CHECK (max_score BETWEEN 1 AND 100),
    content_hash text NOT NULL CHECK (content_hash ~ '^[0-9a-f]{64}$'),
    created_by uuid,
    created_at timestamptz NOT NULL,
    publication_state text NOT NULL DEFAULT 'ACTIVE' CHECK (publication_state IN ('PENDING','ACTIVE','ABORTING')),
    publication_error_code text,
    publication_locked_until timestamptz,
    publication_lease_token uuid,
    publication_next_attempt_at timestamptz,
    publication_attempts integer NOT NULL DEFAULT 0 CHECK (publication_attempts >= 0),
    UNIQUE (task_id,version),
    UNIQUE (task_id,id),
    CHECK ((answer_type = 'FILES') = (correct_answer IS NULL)),
    CHECK (correct_answer IS NULL OR jsonb_typeof(correct_answer) = 'object'),
    CHECK ((publication_locked_until IS NULL) = (publication_lease_token IS NULL))
);

