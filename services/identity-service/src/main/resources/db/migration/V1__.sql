CREATE SEQUENCE IF NOT EXISTS revinfo_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE app_user
(
    id             UUID         NOT NULL,
    login          VARCHAR(255) NOT NULL,
    password_hash  VARCHAR(255) NOT NULL,
    first_name     VARCHAR(255),
    surname        TEXT,
    patronymic     TEXT,
    policy_version VARCHAR(255),
    blocked        BOOLEAN      NOT NULL,
    created_at     TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    name_requested BOOLEAN      NOT NULL,
    CONSTRAINT pk_app_user PRIMARY KEY (id)
);

CREATE TABLE invitation_code
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    code_hash  VARCHAR(255)                            NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    expired_at TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    CONSTRAINT pk_invitation_code PRIMARY KEY (id)
);

CREATE TABLE parent_student
(
    parent_id  UUID NOT NULL,
    student_id UUID NOT NULL,
    CONSTRAINT pk_parent_student PRIMARY KEY (parent_id, student_id)
);

CREATE TABLE revchanges
(
    rev        BIGINT NOT NULL,
    entityname VARCHAR(255)
);

CREATE TABLE revinfo
(
    rev      BIGINT NOT NULL,
    revtstmp BIGINT,
    CONSTRAINT pk_revinfo PRIMARY KEY (rev)
);

CREATE TABLE student_profile
(
    user_id      UUID NOT NULL,
    password     TEXT NOT NULL,
    school_grade SMALLINT,
    CONSTRAINT pk_student_profile PRIMARY KEY (user_id)
);

CREATE TABLE student_reg_request
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    parent_id  UUID                                    NOT NULL,
    first_name TEXT                                    NOT NULL,
    surname    TEXT                                    NOT NULL,
    patronymic TEXT,
    status     TEXT                                    NOT NULL,
    student_id UUID,
    CONSTRAINT pk_student_reg_request PRIMARY KEY (id)
);

CREATE TABLE teacher_registration_code
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    code_hash  TEXT                                    NOT NULL,
    created_at TIMESTAMP with time zone                NOT NULL,
    expired_at TIMESTAMP with time zone                NOT NULL,
    CONSTRAINT pk_teacher_registration_code PRIMARY KEY (id)
);

CREATE TABLE user_role
(
    user_id UUID NOT NULL,
    role    TEXT NOT NULL,
    CONSTRAINT pk_user_role PRIMARY KEY (user_id, role)
);

