CREATE TABLE invitation_idempotency
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         UUID NOT NULL REFERENCES app_user (id),
    operation       VARCHAR(32) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    result_code     TEXT NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    expired_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uc_invitation_idempotency_request UNIQUE (user_id, operation, idempotency_key)
);

CREATE INDEX idx_invitation_idempotency_expired_at
    ON invitation_idempotency (expired_at);
