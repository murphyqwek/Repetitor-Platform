package tutor.educationservice.integration.storage;

import io.minio.CopyObjectArgs;
import io.minio.CopySource;
import io.minio.GetObjectArgs;
import io.minio.MinioClient;
import io.minio.PutObjectArgs;
import io.minio.RemoveObjectArgs;
import io.minio.StatObjectArgs;
import io.minio.errors.ErrorResponseException;
import java.io.BufferedInputStream;
import java.io.InputStream;
import java.util.Objects;

public class MinioObjectStorage implements ObjectStorage {
    private final MinioClient client;
    private final String bucket;

    public MinioObjectStorage(MinioClient client, StorageProperties properties) {
        this.client = client;
        this.bucket = properties.bucket();
    }

    @Override
    public void put(String objectKey, InputStream body, long size, String contentType) {
        Objects.requireNonNull(body, "Object body is required");
        try (InputStream stream = new BufferedInputStream(body)) {
            validateKey(objectKey);
            ObjectMetadata metadata = new ObjectMetadata(size, contentType);
            client.putObject(PutObjectArgs.builder().bucket(bucket).object(objectKey)
                    .stream(stream, metadata.size(), size == -1 ? 10 * 1024 * 1024 : -1)
                    .contentType(metadata.contentType()).build());
        } catch (IllegalArgumentException exception) {
            throw exception;
        } catch (Exception exception) {
            throw translate(exception);
        }
    }

    @Override
    public InputStream get(String objectKey) {
        validateKey(objectKey);
        try {
            return new BufferedInputStream(client.getObject(GetObjectArgs.builder().bucket(bucket).object(objectKey).build()));
        } catch (Exception exception) {
            throw translate(exception);
        }
    }

    @Override
    public void copy(String sourceKey, String targetKey) {
        validateKey(sourceKey);
        validateKey(targetKey);
        try {
            client.copyObject(CopyObjectArgs.builder().bucket(bucket).object(targetKey)
                    .source(CopySource.builder().bucket(bucket).object(sourceKey).build()).build());
        } catch (Exception exception) {
            throw translate(exception);
        }
    }

    @Override
    public void delete(String objectKey) {
        validateKey(objectKey);
        try {
            client.removeObject(RemoveObjectArgs.builder().bucket(bucket).object(objectKey).build());
        } catch (Exception exception) {
            if (!missingObject(exception)) {
                throw translate(exception);
            }
        }
    }

    @Override
    public boolean exists(String objectKey) {
        validateKey(objectKey);
        try {
            client.statObject(StatObjectArgs.builder().bucket(bucket).object(objectKey).build());
            return true;
        } catch (Exception exception) {
            if (missingObject(exception)) {
                return false;
            }
            throw translate(exception);
        }
    }

    private static void validateKey(String key) {
        if (key == null || !key.matches("(?:materials|tmp)/[a-f0-9-]{36}|chat/[a-f0-9-]{36}/[a-f0-9-]{36}")) {
            throw new IllegalArgumentException("Object key must be generated by ObjectKeys");
        }
    }

    private static boolean missingObject(Exception exception) {
        return exception instanceof ErrorResponseException response
                && ("NoSuchKey".equals(response.errorResponse().code()) || "NoSuchObject".equals(response.errorResponse().code()));
    }

    private static StorageException translate(Exception exception) {
        return new StorageException(missingObject(exception) ? StorageException.Reason.NOT_FOUND : StorageException.Reason.UNAVAILABLE);
    }
}
